export function t(key: string, lang: Lang): string {
  const e = D[key]
  if (!e) return key
  return lang === 'fa' ? e[0] : e[1]
}

export const fmtMoney = (n: number, lang: Lang) => {
  const s = new Intl.NumberFormat(lang === 'fa' ? 'fa-IR' : 'en-US').format(Math.round(n))
  return `${s} ${t('toman', lang)}`
}

