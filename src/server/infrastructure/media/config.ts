// ── BabaHakim Backend · Media Engine Policy (PHASE 10, ED-107) ─────────────
// Single source of truth for every file/media limit and allowlist.
// Nothing else in the codebase may hard-code a size limit or a MIME list.
//
// Classification (ED-106):
//   PUBLIC    — anonymously fetchable renditions (product images, public docs)
//   PRIVATE   — auth + ownership/permission + (optionally) signed URL (medical)
//   TEMPORARY — PRIVATE semantics + expiresAt deadline, auto-purged after it
//
// Size limits are per-category and per-role (staff gets more headroom for
// archival originals). All byte values are exact; UI shows MB approximations.
export type AccessClass = 'PUBLIC' | 'PRIVATE' | 'TEMPORARY'
export type LifecycleState = 'ACTIVE' | 'ARCHIVED' | 'DELETED' | 'PURGED'
export type FileStatus = 'PENDING' | 'PROCESSING' | 'READY' | 'REJECTED' | 'INFECTED' | 'FAILED'
export type ScanStatus = 'PENDING' | 'CLEAN' | 'INFECTED' | 'SUSPECT'
export type MediaCategory =
  | 'MEDICAL_IMAGE' | 'PRODUCT_IMAGE' | 'RECEIPT' | 'DELIVERY_PROOF' | 'AVATAR' | 'DOCUMENT'
export type MediaType = 'TONGUE' | 'FACE' | 'RECEIPT' | 'DELIVERY' | 'PRODUCT' | 'AVATAR' | 'DOCUMENT'
export type MediaVariant = 'original' | 'compressed' | 'ai' | 'thumb'

const MB = 1024 * 1024

/** Roles allowed to bypass the patient size ceiling (archival headroom). */
const STAFF_ROLES = new Set(['ADMIN', 'EXPERT_1', 'EXPERT_2', 'DOCTOR', 'OPERATOR'])

export interface CategoryPolicy {
  /** Domain types accepted for this category. */
  types: readonly MediaType[]
  /** Allowed MIME types (declared AND magic-byte detected must both be in it). */
  mimes: readonly string[]
  /** Patient-facing limit in bytes. */
  patientMaxBytes: number
  /** Staff limit in bytes (archival originals). */
  staffMaxBytes: number
  /** Default classification when the caller does not force one. */
  defaultAccessClass: AccessClass
  /** Derived renditions generated by the worker (images only). */
  variants: readonly MediaVariant[]
  /** Variants an anonymous caller may fetch for PUBLIC files. */
  publicVariants: readonly MediaVariant[]
}

