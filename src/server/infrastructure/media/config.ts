export type CategoryKey = keyof typeof MEDIA_POLICY.categories

export function isMediaCategory(v: string): v is CategoryKey {
  return Object.prototype.hasOwnProperty.call(MEDIA_POLICY.categories, v)
}

export function categoryPolicy(category: string): CategoryPolicy {
  if (!isMediaCategory(category)) throw new Error(`unknown media category: ${category}`)
  return MEDIA_POLICY.categories[category as CategoryKey] as CategoryPolicy
}

/** Effective size limit for (category, role). Single source — ED-107. */
export function maxBytesFor(category: CategoryKey, role: string): number {
  const p = MEDIA_POLICY.categories[category] as CategoryPolicy
  return STAFF_ROLES.has(role) ? p.staffMaxBytes : p.patientMaxBytes
}

/** Validate category + type pairing (guarded, throws nothing). */
export function typeAllowedFor(category: CategoryKey, type: string): boolean {
  return (MEDIA_POLICY.categories[category].types as readonly string[]).includes(type)
}

/** Resolve the effective access class honoring the category default. */
export function resolveAccessClass(category: string, requested?: string | null): AccessClass {
  if (!isMediaCategory(category)) return 'PRIVATE' // unknown categories are never public
  const def = MEDIA_POLICY.categories[category].defaultAccessClass as AccessClass
  if (!requested) return def
  if (requested !== 'PUBLIC' && requested !== 'PRIVATE' && requested !== 'TEMPORARY') return def
  // MEDICAL_IMAGE is always PRIVATE — medical data is never public (ED-66)
  if (category === 'MEDICAL_IMAGE' && requested !== 'PRIVATE') return 'PRIVATE'
  return requested as AccessClass
}

