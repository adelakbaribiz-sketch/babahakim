/** Map engine FileStatus onto the legacy MedicalImage status vocabulary. */
export function toMedicalStatus(s: FileStatus): 'PENDING' | 'VALIDATED' | 'REJECTED' | 'PROCESSED' {
  if (s === 'READY') return 'VALIDATED'
  if (s === 'REJECTED' || s === 'INFECTED' || s === 'FAILED') return 'REJECTED'
  return 'PENDING'
}
